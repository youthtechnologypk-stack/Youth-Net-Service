import * as XLSX from 'xlsx';
import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { sanitizeSpreadsheetCell } from './settlementLedgerExport';
import {
  DailyCashReportSummary,
  DailyReportFilterState,
  describeDailyReportFilter,
} from '../services/dailyCashReportService';

export interface DailyCashReportExportParams {
  companyName: string;
  filter: DailyReportFilterState;
  summary: DailyCashReportSummary;
  generatedBy: string;
}

function slugPeriod(filter: DailyReportFilterState): string {
  if (filter.mode === 'day') return filter.day || 'Day';
  if (filter.mode === 'month') return filter.month || 'Month';
  if (filter.mode === 'range') return `${filter.startDate || 'Start'}_to_${filter.endDate || 'End'}`;
  return 'All_Time';
}

function fmtRs(val: number): string {
  const num = Number(val) || 0;
  const sign = num < 0 ? '-' : '';
  return `${sign}Rs. ${Math.abs(Math.round(num)).toLocaleString('en-US')}`;
}

export function exportDailyCashReportToExcel(params: DailyCashReportExportParams): string {
  const { companyName, filter, summary, generatedBy } = params;
  const periodLabel = describeDailyReportFilter(filter);
  const generatedAt = new Date().toLocaleString('en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });

  const wb = XLSX.utils.book_new();

  // Sheet 1: Summary + Combined Statement
  const summaryRows: Array<Array<string | number>> = [
    [sanitizeSpreadsheetCell(`${companyName} — Daily Cash, Expense & Collection Report`)],
    ['Reporting Period', sanitizeSpreadsheetCell(periodLabel), 'Generated By', sanitizeSpreadsheetCell(generatedBy)],
    ['Generated At', sanitizeSpreadsheetCell(generatedAt), 'Status', 'Verified Audit Statement'],
    [],
    ['KPI Metric', 'Amount (PKR)', 'Count / Notes'],
    ['Total Daily Collections', summary.totalCollections, `${summary.collectionsCount} verified payment(s)`],
    ['Total Daily Expenses', summary.totalExpenses, `${summary.expensesCount} expense entry(ies)`],
    ['Net Daily Cash-in-Hand (Collections - Expenses)', summary.netCashInHand, summary.netCashInHand >= 0 ? 'Positive Cash Surplus' : 'Cash Deficit'],
    ['Pending / Uncollected Dues', summary.pendingDues, 'Unpaid / Partial Invoices in Period'],
    [],
    ['--- ITEMIZED DAILY EXPENSES ---'],
    ['Date', 'Category', 'Description', 'Paid By', 'Payment Method', 'Recorded By', 'Amount (Rs.)'],
    ...summary.filteredExpenses.map((e) => [
      sanitizeSpreadsheetCell(e.expense_date),
      sanitizeSpreadsheetCell(e.category),
      sanitizeSpreadsheetCell(e.description),
      sanitizeSpreadsheetCell(e.paid_by),
      sanitizeSpreadsheetCell(e.payment_method),
      sanitizeSpreadsheetCell(e.recorded_by),
      Number(e.amount) || 0,
    ]),
    ['', '', '', '', '', 'TOTAL EXPENSES', summary.totalExpenses],
    [],
    ['--- ITEMIZED CLIENT COLLECTIONS ---'],
    ['Date', 'Invoice #', 'Subscriber Username', 'Collected By', 'Payment Method', 'Notes', 'Amount (Rs.)'],
    ...summary.filteredCollections.map((c) => [
      sanitizeSpreadsheetCell(c.date),
      sanitizeSpreadsheetCell(c.invoiceNo),
      sanitizeSpreadsheetCell(c.subscriberUsername),
      sanitizeSpreadsheetCell(c.collectedBy),
      sanitizeSpreadsheetCell(c.paymentMethod),
      sanitizeSpreadsheetCell(c.notes || '—'),
      Number(c.amount) || 0,
    ]),
    ['', '', '', '', '', 'TOTAL COLLECTIONS', summary.totalCollections],
  ];

  const wsSummary = XLSX.utils.aoa_to_sheet(summaryRows);
  wsSummary['!cols'] = [
    { wch: 16 },
    { wch: 24 },
    { wch: 32 },
    { wch: 20 },
    { wch: 18 },
    { wch: 24 },
    { wch: 16 },
  ];
  XLSX.utils.book_append_sheet(wb, wsSummary, 'Daily Cash Report');

  const filename = `YouthNet_Daily_Cash_Report_${slugPeriod(filter)}.xlsx`;
  XLSX.writeFile(wb, filename);
  return filename;
}

export function exportDailyCashReportToPdf(params: DailyCashReportExportParams): string {
  const { companyName, filter, summary, generatedBy } = params;
  const periodLabel = describeDailyReportFilter(filter);
  const generatedAt = new Date().toLocaleString('en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });

  const doc = new jsPDF({ orientation: 'portrait', unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 36;

  // Header Banner (Clean crisp white A4 audit styling with dark slate accent header)
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, pageWidth, 74, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text(companyName || 'Youth Net Service', margin, 32);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(148, 163, 184);
  doc.text('Daily Cash, Expense & Collection Audit Statement', margin, 50);

  doc.setTextColor(56, 189, 248);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text(`Period: ${periodLabel}`, pageWidth - margin, 32, { align: 'right' });
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(203, 213, 225);
  doc.setFontSize(8.5);
  doc.text(`Generated: ${generatedAt} · By: ${generatedBy}`, pageWidth - margin, 50, { align: 'right' });

  // KPI Summary Table
  autoTable(doc, {
    startY: 88,
    margin: { left: margin, right: margin },
    head: [['Total Daily Collections', 'Total Daily Expenses', 'Net Daily Cash-in-Hand', 'Pending / Uncollected Dues']],
    body: [[
      fmtRs(summary.totalCollections),
      fmtRs(summary.totalExpenses),
      fmtRs(summary.netCashInHand),
      fmtRs(summary.pendingDues),
    ]],
    theme: 'grid',
    headStyles: {
      fillColor: [30, 41, 59],
      textColor: [241, 245, 249],
      fontStyle: 'bold',
      fontSize: 8.5,
      halign: 'center',
    },
    bodyStyles: {
      fontSize: 11,
      fontStyle: 'bold',
      halign: 'center',
      textColor: [15, 23, 42],
      cellPadding: 8,
    },
    columnStyles: {
      0: { textColor: [5, 150, 105] },
      1: { textColor: [225, 29, 72] },
      2: { textColor: summary.netCashInHand >= 0 ? [2, 132, 199] : [225, 29, 72] },
      3: { textColor: [217, 119, 6] },
    },
  });

  let nextY = (doc as any).lastAutoTable?.finalY ? (doc as any).lastAutoTable.finalY + 18 : 165;

  // Section 1: Itemized Client Collections
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text(`1. Client Collections (${summary.collectionsCount} transactions — ${fmtRs(summary.totalCollections)})`, margin, nextY);

  autoTable(doc, {
    startY: nextY + 6,
    margin: { left: margin, right: margin },
    head: [['Date', 'Invoice #', 'Subscriber', 'Collected By', 'Method', 'Amount']],
    body:
      summary.filteredCollections.length > 0
        ? summary.filteredCollections.map((c) => [
            c.date,
            c.invoiceNo,
            c.subscriberUsername,
            c.collectedBy,
            c.paymentMethod,
            fmtRs(c.amount),
          ])
        : [['—', '—', 'No client collections recorded in this period', '—', '—', 'Rs. 0']],
    theme: 'striped',
    headStyles: { fillColor: [5, 150, 105], textColor: [255, 255, 255], fontSize: 8.5 },
    bodyStyles: { fontSize: 8, textColor: [30, 41, 59] },
    columnStyles: { 5: { halign: 'right', fontStyle: 'bold' } },
  });

  nextY = (doc as any).lastAutoTable?.finalY ? (doc as any).lastAutoTable.finalY + 20 : nextY + 80;

  // Section 2: Itemized Daily Expenses
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text(`2. Daily Expenses (${summary.expensesCount} entries — ${fmtRs(summary.totalExpenses)})`, margin, nextY);

  autoTable(doc, {
    startY: nextY + 6,
    margin: { left: margin, right: margin },
    head: [['Date', 'Category', 'Description', 'Paid By', 'Method', 'Amount']],
    body:
      summary.filteredExpenses.length > 0
        ? summary.filteredExpenses.map((e) => [
            e.expense_date,
            e.category,
            e.description,
            e.paid_by,
            e.payment_method,
            fmtRs(e.amount),
          ])
        : [['—', '—', 'No daily expenses logged in this period', '—', '—', 'Rs. 0']],
    theme: 'striped',
    headStyles: { fillColor: [225, 29, 72], textColor: [255, 255, 255], fontSize: 8.5 },
    bodyStyles: { fontSize: 8, textColor: [30, 41, 59] },
    columnStyles: { 5: { halign: 'right', fontStyle: 'bold' } },
  });

  // Signature Footer
  let sigY = ((doc as any).lastAutoTable?.finalY || 500) + 46;
  const pageHeight = doc.internal.pageSize.getHeight();
  if (sigY > pageHeight - 70) {
    doc.addPage();
    sigY = 80;
  }

  doc.setDrawColor(148, 163, 184);
  doc.setLineWidth(0.75);
  // Left signature: Cashier / Accountant
  doc.line(margin, sigY, margin + 170, sigY);
  // Right signature: Master Admin / Director
  doc.line(pageWidth - margin - 170, sigY, pageWidth - margin, sigY);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(51, 65, 85);
  doc.text('Cashier / Operations Manager Signature', margin, sigY + 14);
  doc.text('Master Admin / Director Verification', pageWidth - margin, sigY + 14, { align: 'right' });

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(100, 116, 139);
  doc.text(`Prepared by: ${generatedBy} · Net Cash-in-Hand: ${fmtRs(summary.netCashInHand)}`, margin, sigY + 28);

  const filename = `YouthNet_Daily_Cash_Report_${slugPeriod(filter)}.pdf`;
  doc.save(filename);
  return filename;
}
